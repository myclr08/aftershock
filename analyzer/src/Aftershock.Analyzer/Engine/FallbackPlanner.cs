using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace Aftershock.Analyzer.Engine;

public static class FallbackKinds
{
    public const string BuildFile = "buildFile";
    public const string FallbackGlob = "fallbackGlob";
    public const string EntryPoint = "entryPoint";
    public const string DiRegistration = "diRegistration";
    public const string NotInWorkspace = "notInWorkspace";
    public const string UnsupportedFile = "unsupportedFile";
    public const string BfsLimit = "bfsLimit";
    public const string Timeout = "timeout";
    public const string Error = "error";
    public const string AssemblySetup = "assemblySetup";
}

public abstract record FileDisposition;

/// <summary>Analyze member by member.</summary>
public sealed record SelectiveDisposition(IReadOnlyList<DocumentId> NewDocuments, IReadOnlyList<Project> OwningProjects) : FileDisposition;

/// <summary>Run every test project that depends on <see cref="Projects"/>.</summary>
public sealed record FallbackDisposition(string Kind, string Message, IReadOnlyList<Project> Projects) : FileDisposition;

/// <summary>Not relevant for tests (documentation, unrelated files).</summary>
public sealed record IgnoredDisposition(string Note) : FileDisposition;

/// <summary>Decides, per changed file, between member-level analysis and a whole-test-project fallback.</summary>
public static class FallbackPlanner
{
    private static readonly HashSet<string> DirectoryScopedFiles = new(StringComparer.OrdinalIgnoreCase)
    {
        "Directory.Build.props", "Directory.Build.targets", "Directory.Build.rsp", "Directory.Packages.props",
        "Directory.Solution.props", "Directory.Solution.targets", "global.json", "nuget.config",
    };

    private static readonly HashSet<string> ProjectFileExtensions = new(StringComparer.OrdinalIgnoreCase)
    {
        ".csproj", ".vbproj", ".fsproj", ".proj", ".projitems", ".shproj",
    };

    private static readonly HashSet<string> NonCSharpSourceExtensions = new(StringComparer.OrdinalIgnoreCase)
    {
        ".vb", ".fs", ".razor", ".cshtml", ".xaml", ".resx", ".settings", ".tt",
    };

    private static readonly HashSet<string> EntryPointFiles = new(StringComparer.OrdinalIgnoreCase)
    {
        "Program.cs", "Startup.cs",
    };

    // Build output and tool folders: generated by restore/build, never an input of the change.
    private static readonly HashSet<string> GeneratedFolders = new(StringComparer.OrdinalIgnoreCase)
    {
        "bin", "obj", "TestResults", ".vs", ".idea", ".git",
    };

    public static FileDisposition Classify(FileChange change, SolutionModel model, IReadOnlyList<GlobMatcher> fallbackGlobs, string globRoot, string solutionDirectory)
    {
        var path = change.Path;
        var fileName = Path.GetFileName(path);
        var oldFileName = change.OldPath is null ? fileName : Path.GetFileName(change.OldPath);
        var extension = Path.GetExtension(path);
        var display = change.Display;

        if (IsInGeneratedFolder(path, globRoot) || (change.OldPath is not null && IsInGeneratedFolder(change.OldPath, globRoot)))
        {
            return new IgnoredDisposition("build output or tool folder");
        }

        // 1. Build inputs.
        if (ProjectFileExtensions.Contains(extension))
        {
            var projects = model.ProjectsWithFile(path);
            if (projects.Count == 0 && change.OldPath is not null)
            {
                projects = model.ProjectsWithFile(change.OldPath);
            }

            return projects.Count > 0
                ? new FallbackDisposition(FallbackKinds.BuildFile, $"project file changed: {display}", projects)
                : new IgnoredDisposition("project file is not part of the solution");
        }

        if (DirectoryScopedFiles.Contains(fileName) || DirectoryScopedFiles.Contains(oldFileName))
        {
            var directory = Path.GetDirectoryName(path)!;
            var projects = model.ProjectsUnder(directory);
            return projects.Count > 0
                ? new FallbackDisposition(FallbackKinds.BuildFile, $"build configuration changed: {display} (applies to projects below its folder)", projects)
                : new IgnoredDisposition("build configuration file does not apply to any project of the solution");
        }

        if (extension.Equals(".props", StringComparison.OrdinalIgnoreCase) || extension.Equals(".targets", StringComparison.OrdinalIgnoreCase))
        {
            // Explicitly imported MSBuild files can be imported from anywhere: assume everything.
            var projects = model.Solution.Projects.ToList();
            return new FallbackDisposition(FallbackKinds.BuildFile, $"imported MSBuild file changed: {display}", projects);
        }

        if (fileName.Equals("packages.lock.json", StringComparison.OrdinalIgnoreCase))
        {
            var projects = model.OwningProjects(path);
            return projects.Count > 0
                ? new FallbackDisposition(FallbackKinds.BuildFile, $"package lock file changed: {display}", projects)
                : new IgnoredDisposition("lock file is not owned by a project of the solution");
        }

        // 2. Configured fallback globs (appsettings*.json by default).
        var relativeToRoot = PathUtil.ToGitPath(globRoot, path);
        var relativeToSolution = PathUtil.ToGitPath(solutionDirectory, path);
        var glob = fallbackGlobs.FirstOrDefault(g => g.IsMatch(relativeToRoot) || g.IsMatch(relativeToSolution));
        if (glob is not null)
        {
            var projects = model.OwningProjects(path);
            return projects.Count > 0
                ? new FallbackDisposition(FallbackKinds.FallbackGlob, $"{display} matches fallback glob '{glob.Pattern}'", projects)
                : new IgnoredDisposition($"matches fallback glob '{glob.Pattern}' but no project of the solution owns it");
        }

        // 3. C# sources.
        if (change.IsCSharp)
        {
            var documents = model.DocumentsAt(path);
            var owning = documents.Count > 0
                ? documents.Select(id => model.Solution.GetProject(id.ProjectId)).OfType<Project>().ToList()
                : model.OwningProjects(path).Where(p => p.Language == LanguageNames.CSharp).ToList();

            if (EntryPointFiles.Contains(fileName) || EntryPointFiles.Contains(oldFileName))
            {
                return owning.Count > 0
                    ? new FallbackDisposition(FallbackKinds.EntryPoint, $"application entry point changed: {display}", owning)
                    : new IgnoredDisposition("entry point file is not owned by a project of the solution");
            }

            if (ContainsServiceCollectionExtension(change.NewText) || ContainsServiceCollectionExtension(change.OldText))
            {
                return owning.Count > 0
                    ? new FallbackDisposition(FallbackKinds.DiRegistration, $"dependency injection registration changed (IServiceCollection extension): {display}", owning)
                    : new IgnoredDisposition("DI registration file is not owned by a project of the solution");
            }

            if (change.Kind == FileChangeKind.Deleted)
            {
                return owning.Count > 0
                    ? new SelectiveDisposition(Array.Empty<DocumentId>(), owning)
                    : new IgnoredDisposition("deleted file was not owned by a project of the solution");
            }

            if (documents.Count == 0)
            {
                return owning.Count > 0
                    ? new FallbackDisposition(FallbackKinds.NotInWorkspace, $"{display} is not part of the loaded workspace (excluded from compilation or project failed to load)", owning)
                    : new IgnoredDisposition("C# file outside every project of the solution");
            }

            return new SelectiveDisposition(documents, owning);
        }

        // 4. Other sources that compile into assemblies.
        if (NonCSharpSourceExtensions.Contains(extension))
        {
            var projects = model.OwningProjects(path);
            return projects.Count > 0
                ? new FallbackDisposition(FallbackKinds.UnsupportedFile, $"non-C# source or resource changed: {display}", projects)
                : new IgnoredDisposition("not owned by a project of the solution");
        }

        return new IgnoredDisposition("not a source or build file");
    }

    private static bool IsInGeneratedFolder(string path, string root)
    {
        var relative = PathUtil.IsUnder(path, root) ? Path.GetRelativePath(root, path) : path;
        var segments = relative.Split(new[] { Path.DirectorySeparatorChar, Path.AltDirectorySeparatorChar }, StringSplitOptions.RemoveEmptyEntries);
        return segments.Take(Math.Max(0, segments.Length - 1)).Any(GeneratedFolders.Contains);
    }

    /// <summary>True when the text declares an extension method on IServiceCollection (a DI registration file).</summary>
    public static bool ContainsServiceCollectionExtension(string? text)
    {
        if (string.IsNullOrEmpty(text) || !text.Contains("IServiceCollection", StringComparison.Ordinal))
        {
            return false;
        }

        var root = CSharpSyntaxTree.ParseText(text).GetRoot();
        foreach (var method in root.DescendantNodes().OfType<MethodDeclarationSyntax>())
        {
            var first = method.ParameterList.Parameters.FirstOrDefault();
            if (first is null || !first.Modifiers.Any(SyntaxKind.ThisKeyword) || first.Type is null)
            {
                continue;
            }

            var typeName = first.Type switch
            {
                QualifiedNameSyntax qualified => qualified.Right.Identifier.ValueText,
                IdentifierNameSyntax identifier => identifier.Identifier.ValueText,
                AliasQualifiedNameSyntax alias => alias.Name.Identifier.ValueText,
                _ => first.Type.ToString(),
            };

            if (typeName == "IServiceCollection")
            {
                return true;
            }
        }

        return false;
    }
}
